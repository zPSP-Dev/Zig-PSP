const std = @import("std");

// This takes a PRX file as input and outputs a PSP executable.
// It uses the header of an officially encrypted PRX which we can't edit (see HEADER_SETS)
// We then encrypt our own PRX payload in such a way that is matches the header's declared PRX size and CMAC hashes.
// This is why there's a size limit on the input PRX. We pad with zeroes in the opposite case.
// Once done we just write the immutable header followed by the encrypted payload, and the PSP loader accepts it as a valid PRX.
pub fn encrypt(allocator: std.mem.Allocator, prx_reader: *std.Io.Reader, input_prx_size: usize, psp_writer: *std.Io.Writer) !void {
    const magic = prx_reader.peek(4) catch |err| {
        std.debug.print("error: failed to read magic\n", .{});
        return err;
    };

    if (!std.mem.eql(u8, magic, PRX_MAGIC)) {
        std.debug.print("error: invalid magic: got '{s}', expected '{s}'\n", .{ magic, PRX_MAGIC });
        return error.InvalidMagic;
    }

    const headers = for (HEADER_SETS) |header_set| {
        if (input_prx_size <= header_set.psp_full_header.psp_header.prx_size) {
            break header_set;
        }
    } else {
        // We can't change the header's declared prx_size without breaking the CMAC, so reject large PRXs upfront.
        // Smaller PRX files will fit because we just pad with zeros later!
        std.debug.print("error: invalid PRX size: {} is too big\n", .{input_prx_size});
        return error.PRXTooLarge;
    };

    // Verify the hardcoded header can accommodate the loaded PRX
    const psp_full_header = headers.psp_full_header;
    const psp_header = psp_full_header.psp_header;

    // Override our PRX size with the original header one. We pad with zeros.
    const prx_size = psp_header.prx_size;

    const compressed_prx_buf = try allocator.alloc(u8, prx_size); // Allocate for worst case
    defer allocator.free(compressed_prx_buf);

    @memset(compressed_prx_buf, 0);

    switch (psp_header.compression_attributes) {
        .NONE => {
            // No compression, just copy the PRX as-is.
            const read_bytes = try prx_reader.readSliceShort(compressed_prx_buf);
            std.debug.assert(read_bytes == input_prx_size);
        },
        .COMPRESSED => {
            // Gzip-compress prx using std.compress.
            // std's gzip header is constant, so output is deterministic.

            // Growing output writer backed by the arena; pre-size to prx_size as upper bound
            var gzip_allocating_writer = try std.Io.Writer.Allocating.initCapacity(allocator, input_prx_size);
            defer gzip_allocating_writer.deinit();

            // History window required by the compressor (minimum flate.max_window_len = 65536 bytes)
            const window = try allocator.alloc(u8, std.compress.flate.max_window_len);
            defer allocator.free(window);

            var compressor = try std.compress.flate.Compress.init(
                &gzip_allocating_writer.writer,
                window,
                .gzip,
                .best,
            );

            const input_ingested_bytes = try prx_reader.streamRemaining(&compressor.writer);
            std.debug.assert(input_ingested_bytes == input_prx_size);

            try compressor.writer.splatByteAll(0, prx_size - input_prx_size); // Pad with zeros if PRX is smaller than header's declared size
            try compressor.finish();

            const c_size = gzip_allocating_writer.writer.end;
            const compressed = gzip_allocating_writer.writer.buffer[0..c_size];

            // Copy compressed output back over the original PRX region
            @memcpy(compressed_prx_buf[0..c_size], compressed);
        },
        else => {
            std.debug.print("error: unsupported compression flags: {}\n", .{psp_header.compression_attributes});
            return error.UnsupportedCompressionFlags;
        },
    }

    const kirk_raw = try allocator.alloc(u8, prx_size + 0x110);
    defer allocator.free(kirk_raw);

    const aligned_kirk_data_size = std.mem.alignForward(usize, headers.kirk_header.data_size, 0x10) + 0x110;

    // Build kirk_raw: copy the 0x110-byte kirk header prefix
    @memcpy(kirk_raw[0..0x90], std.mem.asBytes(&headers.kirk_header));
    @memcpy(kirk_raw[0x90..0x110], std.mem.asBytes(&psp_header));
    @memset(kirk_raw[0x110..], 0);

    // Backup the first 0x90 bytes before key decryption
    var raw_header_save: [0x90]u8 = undefined;
    @memcpy(&raw_header_save, kirk_raw[0..0x90]);

    // Decrypt the AES/CMAC keys embedded at the start of the kirk header.
    // AES-128-CBC with zero IV, 2 blocks: decrypt each block then XOR with previous ciphertext.
    var keys: HeaderKeys = undefined;
    {
        const dec = std.crypto.core.aes.Aes128.initDec(KIRK1_KEY);
        dec.decrypt(&keys.aes, kirk_raw[0..16]);
        dec.decrypt(&keys.cmac, kirk_raw[16..32]);

        for (&keys.cmac, kirk_raw[0..16]) |*b, prev| {
            b.* ^= prev;
        }
    }

    // Replace the first 32 bytes of kirk_raw with the decrypted keys so
    // kirk_CMD0 can locate them at the expected offset
    @memcpy(kirk_raw[0..16], &keys.aes);
    @memcpy(kirk_raw[16..32], &keys.cmac);

    // Append PRX (or compressed PRX) after the 0x110-byte header
    @memcpy(kirk_raw[0x110..], compressed_prx_buf);

    const kirk_enc = try allocator.alloc(u8, aligned_kirk_data_size);
    defer allocator.free(kirk_enc);

    @memset(kirk_enc, 0);

    // Encrypt with KIRK CMD0
    kirk_cmd0(kirk_enc, kirk_raw) catch |err| {
        std.debug.print("error: failed to execute CMD0\n", .{});
        return err;
    };

    // Restore the original (pre-decryption) header into the encrypted buffer
    @memcpy(kirk_enc[0..0x90], &raw_header_save);

    // Forge the CMAC signature
    kirk_forge_cmac(kirk_enc, &keys.cmac) catch |err| {
        std.debug.print("error: failed to forge CMAC\n", .{});
        return err;
    };

    // Assemble output: PSP header (0x150 bytes) + encrypted payload
    try psp_writer.writeAll(std.mem.asBytes(&headers.psp_full_header)); // 0..0x150
    try psp_writer.writeAll(kirk_enc[0x110..]); // 0x150..rest
    try psp_writer.flush();
}

const KIRK1_KEY = [16]u8{ 0x98, 0xC9, 0x40, 0x97, 0x5C, 0x1D, 0x10, 0xE8, 0x7F, 0xE6, 0x0E, 0xA3, 0xFD, 0x03, 0xA8, 0xBA };

const PRX_MAGIC = "\x7fELF";

// ~PSP encrypted PRX header
const PSPHeader = extern struct {
    const SCE_KERNEL_MAX_MODULE_SEGMENT = 4;
    const SCE_MODULE_NAME_LEN = 27;

    magic: [4]u8, //0
    modAttribute: u16, //4 The module's attributes. One or more of ::SceModulePrivilegeLevel. */
    compression_attributes: enum(u16) {
        NONE = 0x0, // The file is not compressed
        COMPRESSED = 0x1, // The file is compressed. If SCE_EXEC_FILE_KL4E_COMPRESSED is not set, the file is GZIP compressed. */
        PRX = 0x2, // The file is a static PRX. */
        GZIP_OVERLAP = 0x8, // The file has GZIP overlap. */
        KL4E_COMPRESSED = 0x200, // The file is KL4E compressed. */
    }, // The Compression attributes of the module. One of ::SceExecFileAttr. */
    moduleVerLo: u8, //8 The minor module version. */
    moduleVerHi: u8, //9 The major module version. */
    modName: [SCE_MODULE_NAME_LEN + 1]u8, //10 The module's name. */
    modVersion: u8, //38 Module version. */
    nSegments: u8, //39 The number of segment the module consists of. */
    prx_size: u32, //40 The size of the uncompressed and decrypted module. */
    psp_size: u32, //44 The size of the compressed/encrypted module. */
    boot_entry: u32, //48 The entry address of the module. It is the offset from the start of the TEXT segment to the program's entry point. */
    mod_info_offset: u32, //52 The offset from the start address of the TEXT segment to the SceModuleInfo section. */
    bssSize: u32, //56 The size of the BSS segment. */
    segAlign: [SCE_KERNEL_MAX_MODULE_SEGMENT]u16, //60 An array containing the alignment information of each segment. */
    segAddress: [SCE_KERNEL_MAX_MODULE_SEGMENT]u32, //68 An array containing the start address of each segment. */
    segSize: [SCE_KERNEL_MAX_MODULE_SEGMENT]u32, //84 An array containing the size of each segment. */
    reserved: [5]u32, //100 Reserved. */
    devkitVersion: u32, //120 The development kit version the module was compiled with. */
    decryptMode: u8, //124 The decryption mode. One of ::SceExecFileDecryptMode. */
    padding: u8, //125 Reserved. */
    overlapSize: u16, //126 The overlap size. */
};

const PSPFullHeader = extern struct {
    const AES_KEY_SIZE = 16;
    const CMAC_KEY_SIZE = 16;
    const CMAC_HEADER_HASH_SIZE = 16;
    const CMAC_DATA_HASH_SIZE = 16;
    const SHA1_HASH_SIZE = 20;
    const KEY_DATA_SIZE = 16;
    const CHECK_SIZE = 88;

    psp_header: PSPHeader,
    aesKey: [AES_KEY_SIZE]u8, //128 The AES key data. */
    cmacKey: [CMAC_KEY_SIZE]u8, //144 THE CMAC key data. */
    cmacHeaderHash: [CMAC_HEADER_HASH_SIZE]u8, //160 The CMAC header hash. */
    compSize: u32, //176 The size of the compressed PRX. */
    unk180: u32, //180 Unknown. */
    unk184: u32, //184 Unknown. */
    unk188: u32, //188 Unknown. */
    cmacDataHash: [CMAC_DATA_HASH_SIZE]u8, //192 The CMAC Data hash. */
    tag: u32, //208 Tag value. */
    sCheck: [CHECK_SIZE]u8, //212 Check. */
    sha1Hash: [SHA1_HASH_SIZE]u8, //300 The SHA-1 hash. */
    keyData4: [KEY_DATA_SIZE]u8, //320 Key data. */
};

comptime {
    std.debug.assert(@sizeOf(PSPHeader) == 0x80);
    std.debug.assert(@sizeOf(PSPFullHeader) == 0x150);
}

const KirkHeader = extern struct {
    aes_key: [16]u8, // 0x00
    cmac_key: [16]u8, // 0x10
    cmac_header_hash: [16]u8, // 0x20
    cmac_data_hash: [16]u8, // 0x30
    unused: [32]u8, // 0x40
    mode: u32, // 0x60
    unk3: [12]u8, // 0x64
    data_size: u32, // 0x70
    data_offset: u32, // 0x74
    unk4: [8]u8, // 0x78
    unk5: [16]u8, // 0x80
};

comptime {
    std.debug.assert(@sizeOf(KirkHeader) == 0x90);
    std.debug.assert(@sizeOf(PSPHeader) + @sizeOf(KirkHeader) == 0x110);
}

// Mirrors the header_keys struct in kirk_engine.c (32 bytes, no padding)
const HeaderKeys = extern struct {
    aes: [16]u8,
    cmac: [16]u8,
};

// Zig port of kirk_CMD0 from kirk_engine.c.
// Reads the decrypted AES/CMAC keys from in[0..32], AES-CBC encrypts the data
// section, computes CMAC hashes, then re-encrypts the key block with KIRK1_KEY.
// Note: main restores raw_header_bk over out[0..0x90] after this call, so
// the CMAC and key-reencrypt writes are cosmetic — only the data encrypt matters.
fn kirk_cmd0(out: []u8, in: []const u8) !void {
    const in_kirk_header = std.mem.bytesAsValue(KirkHeader, in[0..0x90]);

    if (in_kirk_header.mode != 1) {
        return error.UnsupportedMode;
    }

    const data_size = in_kirk_header.data_size;
    const data_offset = in_kirk_header.data_offset;

    var chk_size = data_size;
    if (chk_size % 16 != 0) chk_size += 16 - (chk_size % 16);

    const data_start = @sizeOf(KirkHeader) + @as(usize, data_offset);

    // Copy header + pre-data region so CMAC reads from out are coherent
    @memcpy(out[0..data_start], in[0..data_start]);

    // Encrypt data: in[data_start..] → out[data_start..] with decrypted AES key
    aes_cbc_encrypt(in_kirk_header.aes_key, in[data_start..][0..chk_size], out[data_start..][0..chk_size]);

    // CMAC header hash over out[0x60..0x90] → out[0x20..0x30]
    var cmac_header_hash: [16]u8 = undefined;
    std.crypto.auth.cmac.CmacAes128.create(&cmac_header_hash, out[0x60..][0..0x30], out[16..32]);
    @memcpy(out[0x20..][0..16], &cmac_header_hash);

    // CMAC data hash over out[0x60..0x60+0x30+data_offset+chk_size] → out[0x30..0x40]
    const data_cmac_len = @as(usize, 0x30) + @as(usize, data_offset) + chk_size;
    var cmac_data_hash: [16]u8 = undefined;
    std.crypto.auth.cmac.CmacAes128.create(&cmac_data_hash, out[0x60..][0..data_cmac_len], out[16..32]);
    @memcpy(out[0x30..][0..16], &cmac_data_hash);

    // Re-encrypt key block (in[0..32]) with KIRK1_KEY → out[0..32]
    aes_cbc_encrypt(KIRK1_KEY, in[0..32], out[0..32]);
}

// Verifies the CMAC header hash and patches the data region so its CMAC
// matches the stored CMAC_data_hash, without needing Sony's signing key.
// Takes the already-decrypted cmac_key (from the AES-CBC decrypt at line 211)
// so there is no redundant key re-derivation.
fn kirk_forge_cmac(buf: []u8, cmac_key: *const [16]u8) !void {
    const mode = std.mem.readInt(u32, buf[0x60..][0..4], .little);
    const data_size = std.mem.readInt(u32, buf[0x70..][0..4], .little);
    const data_offset = std.mem.readInt(u32, buf[0x74..][0..4], .little);

    if (mode != 1) return error.InvalidMode; // only CMD1 supported
    if (data_size == 0) return error.DataSizeZero;

    // Verify header CMAC (covers bytes 0x60..0x90 of the header)
    var cmac_header_hash: [16]u8 = undefined;
    std.crypto.auth.cmac.CmacAes128.create(&cmac_header_hash, buf[0x60..][0..0x30], cmac_key);
    if (!std.mem.eql(u8, &cmac_header_hash, buf[0x20..][0..16])) return error.HeaderHashInvalid;

    // 16-align data_size for the CMAC region length
    const chk_size = std.mem.alignForward(u32, data_size, 16);
    const data_cmac_len = @as(usize, 0x30) + chk_size + data_offset;

    // Compute actual data CMAC and compare with stored CMAC_data_hash
    var cmac_data_hash: [16]u8 = undefined;
    std.crypto.auth.cmac.CmacAes128.create(&cmac_data_hash, buf[0x60..][0..data_cmac_len], cmac_key);
    const stored_data_hash = buf[0x30..][0..16];
    if (std.mem.eql(u8, &cmac_data_hash, stored_data_hash)) return; // already valid

    // Patch the last 16 bytes of the CMAC region so it produces stored_data_hash
    cmac_forge(cmac_key, buf[0x60..][0..data_cmac_len], stored_data_hash);
}

// Patches the last 16-byte block of `data` so that AES-CMAC(key, data) == target.
// Assumes `data.len` is a multiple of 16 (true for KIRK CMD1 headers).
fn cmac_forge(key: *const [16]u8, data: []u8, target: *const [16]u8) void {
    const Aes128 = std.crypto.core.aes.Aes128;
    const enc = Aes128.initEnc(key.*);
    const dec = Aes128.initDec(key.*);

    // Derive CMAC subkey K1: double(AES(0...0))
    var k1 = [_]u8{0} ** 16;
    enc.encrypt(&k1, &k1);
    k1 = double_block(k1);

    // Run CBC forward over all blocks except the last to get X_{n-1}
    const n = data.len / 16;
    var x = [_]u8{0} ** 16;
    for (0..n - 1) |i| {
        for (&x, data[i * 16 ..][0..16]) |*xb, mb| xb.* ^= mb;
        enc.encrypt(&x, &x);
    }

    // Solve for the last block: M_new = AES_decrypt(target) ^ X_{n-1} ^ K1
    var dec_target: [16]u8 = undefined;
    dec.decrypt(&dec_target, target);
    const last = data[(n - 1) * 16 ..][0..16];
    for (last, dec_target, x, k1) |*b, d, xi, ki| b.* = d ^ xi ^ ki;
}

// Doubles a 128-bit block in GF(2^128) for CMAC subkey derivation.
fn double_block(b: [16]u8) [16]u8 {
    var out: [16]u8 = undefined;
    const msb: u8 = b[0] >> 7;
    for (0..15) |i| out[i] = (b[i] << 1) | (b[i + 1] >> 7);
    out[15] = (b[15] << 1) ^ (0x87 * msb);
    return out;
}

// AES-128-CBC encryption with zero IV. src and dst must be the same length
// and a multiple of 16. src and dst may be different buffers (no in-place).
fn aes_cbc_encrypt(key: [16]u8, src: []const u8, dst: []u8) void {
    const enc = std.crypto.core.aes.Aes128.initEnc(key);
    var iv = [_]u8{0} ** 16;
    var i: usize = 0;
    while (i < src.len) : (i += 16) {
        var block: [16]u8 = undefined;
        for (&block, src[i..][0..16], iv) |*b, s, v| b.* = s ^ v;
        enc.encrypt(&iv, &block);
        @memcpy(dst[i..][0..16], &iv);
    }
}

